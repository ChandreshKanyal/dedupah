"""Reproducible benchmark on SYNTHETIC data: held-out seeds, noise levels, sizes, and an ablation study.

    python -m dedupe.benchmark --out docs/BENCHMARK.md

Tuning (regularisation, thresholds, evidence weights) was done on seeds 42/44/1; the benchmark uses seeds never used
for tuning (101-103). Results here do not establish accuracy on real data.
"""
import argparse
import importlib
import json
import os
import shutil
import tempfile
from pathlib import Path

from .decision import DecisionConfig
from .evaluation import baseline
from .evaluation.loaders import load_truth
from .evaluation.metrics import evaluate
from .pipeline import PipelineConfig, run_pipeline
from .synthetic import generate

HELD_OUT_SEEDS = (101, 102, 103)
NOISE_LEVELS = (0.5, 1.0, 2.0)
SIZES = (300, 1200, 5000)  # households
ABLATION_HOUSEHOLDS, ABLATION_SEED = 1200, 101


def _make_data(root: Path, households: int, seed: int, noise: float):
    syn = root / "syn"
    generate(households, seed, syn, noise)
    cfg = json.loads(Path("configs/synthetic_sources.json").read_text(encoding="utf-8"))
    for s in cfg["sources"]:
        s["connector"]["path"] = str(syn / os.path.basename(s["connector"]["path"]))
    (root / "sources.json").write_text(json.dumps(cfg), encoding="utf-8")
    return syn, root / "sources.json"


def _row(summary: dict) -> dict:
    c, d, h = summary["eval_clusters"], summary["eval_decisions"], summary["eval_households"]["family_only"]
    return {"records": summary["ingest"]["total"], "precision": c["precision"], "recall": c["recall"], "f1": c["f1"],
            "false_merge_pairs": c["fp_pairs"], "impure_clusters": c["impure_clusters"],
            "auto_merge_false": d["zones"]["auto_merge"]["false"], "auto_merge_pairs": d["zones"]["auto_merge"]["pairs"],
            "review_pairs": d["zones"]["review"]["pairs"], "review_real_share": d["zones"]["review"]["true_share"],
            "family_precision": h["precision"], "family_recall": h["recall"], "seconds": summary["total_seconds"],
            "peak_memory_mb": summary["peak_memory_mb"]}


def run_one(households: int, seed: int, noise: float = 1.0, variant: str = "full") -> dict:
    root = Path(tempfile.mkdtemp(prefix="dedupe_bench_"))
    try:
        syn, sources = _make_data(root, households, seed, noise)
        if variant == "baseline":
            pred = baseline.run(syn)
            t, h, tr = load_truth(syn)
            r = evaluate(pred, t, h, tr)
            return {"records": r["records"], "precision": r["precision"], "recall": r["recall"], "f1": r["f1"],
                    "false_merge_pairs": r["fp_pairs"], "impure_clusters": r["impure_clusters"]}
        dec_cfg = Path("configs/decision_default.json")
        kwargs = {}
        if variant == "no_rules":
            dec_cfg = root / "no_rules.json"
            dec_cfg.write_text(DecisionConfig(rules=[]).model_dump_json(), encoding="utf-8")
        if variant == "no_guard":
            kwargs["cluster_guard"] = False
        restore = None
        if variant == "no_term_frequency":
            train = importlib.import_module("dedupe.scoring.train")
            restore = train.TF_CLIP
            train.TF_CLIP = 1.0  # a TF adjustment can no longer change a weight
        try:
            s = run_pipeline(PipelineConfig(sources, root / "work", decision_config=dec_cfg, truth=syn, **kwargs))
        finally:
            if restore is not None:
                importlib.import_module("dedupe.scoring.train").TF_CLIP = restore
        return _row(s)
    finally:
        shutil.rmtree(root, ignore_errors=True)


def _f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def render_markdown(res: dict) -> str:
    L = ["# Benchmark (SYNTHETIC data)", "",
         "Generated by `python -m dedupe.benchmark`. Metrics are pairwise over records, after clustering (person level) unless stated.",
         "Seeds 101-103 were never used for tuning. **These numbers do not prove accuracy on real customer data.**", ""]
    L += ["## 1. Held-out seeds x noise level (1,200 households, about 8k records)", "",
          "| noise | seed | precision | recall | F1 | false-merge pairs | auto-merge false / pairs | review queue (real %) | family P / R | seconds |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in res["noise_seed"]:
        L.append(f"| {r['noise']} | {r['seed']} | {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | {r['false_merge_pairs']} | "
                 f"{r['auto_merge_false']} / {r['auto_merge_pairs']:,} | {r['review_pairs']:,} ({_f(r['review_real_share'], 2)}) | {_f(r['family_precision'], 2)} / {_f(r['family_recall'], 2)} | {r['seconds']} |")
    L += ["", "Mean F1 by noise level: " + ", ".join(f"noise {n}: {_f(m)}" for n, m in res["mean_f1_by_noise"].items()), ""]
    L += ["## 2. Size scaling (noise 1.0, seed 101)", "", "| households | records | precision | recall | F1 | auto-merge false | review queue | family P / R | seconds | peak memory MB |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in res["sizes"]:
        L.append(f"| {r['households']:,} | {r['records']:,} | {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | {r['auto_merge_false']} | {r['review_pairs']:,} | {_f(r['family_precision'], 2)} / {_f(r['family_recall'], 2)} | {r['seconds']} | {r['peak_memory_mb']} |")
    L += ["", f"## 3. Ablation ({ABLATION_HOUSEHOLDS:,} households, seed {ABLATION_SEED}, noise 1.0): what each component contributes", "",
          "| variant | precision | recall | F1 | false-merge pairs | impure clusters | review queue |", "|---|---|---|---|---|---|---|"]
    names = {"baseline": "Naive baseline (exact PAN or mobile)", "full": "**Full pipeline**", "no_rules": "Without decision rules (score zones only)",
             "no_guard": "Without clustering contradiction guard", "no_term_frequency": "Without term-frequency adjustment"}
    for k, r in res["ablation"].items():
        L.append(f"| {names[k]} | {_f(r['precision'])} | {_f(r['recall'])} | {_f(r['f1'])} | {r['false_merge_pairs']} | {r['impure_clusters']} | {r.get('review_pairs', '-')} |")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=Path("docs/BENCHMARK.md"))
    ap.add_argument("--quick", action="store_true", help="fewer runs (one seed, no 5,000-household run)")
    a = ap.parse_args()
    seeds = HELD_OUT_SEEDS[:1] if a.quick else HELD_OUT_SEEDS
    res = {"noise_seed": [], "sizes": [], "ablation": {}}
    for noise in NOISE_LEVELS:
        for seed in seeds:
            print(f"noise {noise} seed {seed} ...", flush=True)
            res["noise_seed"].append({"noise": noise, "seed": seed, **run_one(1200, seed, noise)})
    res["mean_f1_by_noise"] = {n: sum(r["f1"] for r in res["noise_seed"] if r["noise"] == n) / len(seeds) for n in NOISE_LEVELS}
    for hh in SIZES[:2] if a.quick else SIZES:
        print(f"size {hh} ...", flush=True)
        res["sizes"].append({"households": hh, **run_one(hh, ABLATION_SEED, 1.0)})
    for v in ("baseline", "full", "no_rules", "no_guard", "no_term_frequency"):
        print(f"ablation {v} ...", flush=True)
        res["ablation"][v] = run_one(ABLATION_HOUSEHOLDS, ABLATION_SEED, 1.0, v)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(render_markdown(res), encoding="utf-8")
    a.out.with_suffix(".json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    print(render_markdown(res))


if __name__ == "__main__":
    main()
